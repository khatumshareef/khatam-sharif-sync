export type Section = {
  title: string;
  subtitle: string;
  start: number;
  words: { word: Word; index: number }[];
};

export const SECTIONS: Section[] = SECTION_DEFS.map((def, i) => {
  const next = SECTION_DEFS[i + 1]?.from ?? Infinity;
  return {
    title: def.title,
    subtitle: def.subtitle,
    start: def.from,
    words: WORDS.map((word, index) => ({ word, index })).filter(
      ({ word }) => word.start >= def.from && word.start < next,
    ),
  };
});

export const TOTAL_WORDS = WORDS.length;

export function findWordIndexAt(time: number): number {
  let lo = 0;
  let hi = WORDS.length - 1;
  let found = -1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const w = WORDS[mid]!;
    if (time < w.start) hi = mid - 1;
    else if (time >= w.end) lo = mid + 1;
    else {
      found = mid;
      break;
    }
  }
  return found;
}

